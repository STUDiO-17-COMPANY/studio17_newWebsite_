const fs = require('fs');
const path = require('path');

const localeFiles = ['en.json', 'pt-PT.json', 'es.json', 'el.json', 'ru.json', 'he.json'];
const localeData = {};

for (const file of localeFiles) {
  const data = JSON.parse(fs.readFileSync(path.join(__dirname, file), 'utf8'));
  localeData[data.locale] = data;
}

const output = `/* Generated by locales/build-bundle.cjs. Edit the JSON sources, then regenerate. */\nwindow.Studio17LocaleData = ${JSON.stringify(localeData, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, 'locales.js'), output, 'utf8');
