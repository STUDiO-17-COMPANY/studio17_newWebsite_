'use strict';

const assert = require('node:assert/strict');
const os = require('node:os');
const path = require('node:path');
const { chromium } = require('playwright');

const baseUrl = process.env.STUDIO17_TEST_URL || 'http://127.0.0.1:8085';
const languages = ['en', 'pt-PT', 'es', 'el', 'ru', 'he'];
const packageNames = ['One Page Website', 'Starter Pack', 'Growth Pack', 'Business Pack', 'Custom Website'];

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const errors = [];
  try {
    for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 900 } });
      await context.addInitScript(() => localStorage.setItem('studio17-analytics-consent-v1', 'denied'));
      for (const language of languages) {
        const page = await context.newPage();
        page.on('console', message => { if (message.type() === 'error') errors.push(`${language} ${width}: ${message.text()}`); });
        page.on('pageerror', error => errors.push(`${language} ${width}: ${error.message}`));
        await page.goto(`${baseUrl}/services/website-development?lang=${language}`, { waitUntil: 'networkidle' });
        assert.equal(await page.locator('html').getAttribute('lang'), language);
        assert.equal(await page.locator('html').getAttribute('dir'), language === 'he' ? 'rtl' : 'ltr');
        assert.equal(await page.locator('.website-package-card').count(), 5);
        assert.deepEqual(await page.locator('.website-package-card h3').allTextContents(), packageNames);
        assert.equal(await page.locator('.website-package-card.is-popular h3').innerText(), 'Starter Pack');
        assert.equal((await page.locator('.website-package-enterprise .website-package-price span').innerText()).replace(/\u00a0/g, ' '), '3 500,00 €');
        const ctaImage = page.locator('.website-development-cta-media img');
        assert.equal(await ctaImage.getAttribute('src'), '/Images/PhosOpticsWebsiteMainPage.webp');
        await ctaImage.scrollIntoViewIfNeeded();
        await page.waitForFunction(() => document.querySelector('.website-development-cta-media img')?.complete);
        assert.equal(await ctaImage.evaluate(image => image.naturalWidth), 1920);
        assert.equal(await page.locator('.website-development-cta .cta-actions a').count(), 2);
        assert.equal(await page.locator('.website-development-cta .cta-actions .solid-button').count(), 1);
        assert.equal(await page.locator('.website-development-cta .cta-actions .design-link').count(), 1);
        assert.equal(await page.locator('.website-process li').count(), 4);
        assert.equal(await page.locator('.website-process li > span').count(), 0);
        assert.notEqual(await page.locator('.website-process li').first().evaluate(element => getComputedStyle(element, '::after').content), 'none');
        assert.equal(await page.locator('.website-development-main h1, .website-development-main h2').evaluateAll(headings => headings.every(heading => !heading.textContent.trim().endsWith('.'))), true);
        assert.equal(await page.locator('.page-hero-icon:visible').count(), 0);
        const sectionMetrics = await page.locator('.website-work, .website-packages, .website-foundation, .website-process, .website-faq, .website-development-cta').evaluateAll(sections => sections.map(section => {
          const style = getComputedStyle(section);
          return { marginTop: style.marginTop, paddingTop: style.paddingTop, paddingBottom: style.paddingBottom, background: style.backgroundColor };
        }));
        assert.equal(sectionMetrics.every(metric => metric.marginTop === '32px' && metric.paddingTop === '24px' && metric.paddingBottom === '24px' && metric.background === 'rgb(248, 250, 252)'), true, `${language} section rhythm at ${width}px`);
        if (width === 390) assert.match(await page.locator('.website-process li').first().evaluate(element => getComputedStyle(element, '::after').content), /↓/);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, `${language} overflows at ${width}px`);
        if (width === 1440 && language === 'en') await page.screenshot({ path: path.join(os.tmpdir(), 'studio17-website-packages-en.png'), fullPage: true });
        if (width === 390 && language === 'he') await page.screenshot({ path: path.join(os.tmpdir(), 'studio17-website-packages-he-mobile.png'), fullPage: true });
        await page.close();
      }
      await context.close();
    }
    assert.deepEqual(errors, [], `browser errors: ${errors.join(' | ')}`);
    console.log('Website package browser tests passed.');
  } finally {
    await browser.close();
  }
})().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
