const fs = require('node:fs');
const path = require('node:path');

const localeFiles = ['pt-PT.json', 'es.json', 'el.json', 'ru.json', 'he.json'];
const localeData = {};
for (const file of localeFiles) {
  const data = JSON.parse(fs.readFileSync(path.join(__dirname, file), 'utf8'));
  localeData[data.locale] = data.pages;
}
const output = `/* Generated by legal-locales/build-bundle.cjs. Edit the JSON sources, then regenerate. */\nwindow.Studio17LegalLocaleData = ${JSON.stringify(localeData, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, 'locales.js'), output, 'utf8');
